// Generates TypeScript types from rapidtriage/schemas/*.json into src/schemas/.
//
//   npm run gen:schemas              regenerate src/schemas/*.ts
//   npm run gen:schemas -- --check   exit 1 when a committed file is stale, missing or extra (CI)
//
// A schema that fails to compile is an error in --check mode: the committed types would no
// longer describe what the backend emits.

import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, "..", "..", "rapidtriage", "schemas");
const outDir = join(here, "..", "src", "schemas");
const check = process.argv.includes("--check");

const files = (await readdir(schemaDir)).filter((name) => name.endsWith(".schema.json")).sort();
const outputs = new Map();
const failures = [];

for (const file of files) {
  const base = file.replace(/\.schema\.json$/, "");
  try {
    const schema = JSON.parse(await readFile(join(schemaDir, file), "utf-8"));
    const ts = await compile(schema, base.replace(/-/g, "_"), {
      bannerComment: "/* Generated by frontend/scripts/gen-schemas.mjs — do not edit by hand. */",
      format: false,
      strictIndexSignatures: true,
    });
    outputs.set(`${base}.ts`, ts);
  } catch (error) {
    failures.push(file);
    console.error(`skipped ${file}: ${error.message}`);
  }
}

outputs.set(
  "index.ts",
  `// Generated barrel — do not edit by hand.\n${[...outputs.keys()]
    .map((name) => `export * from "./${name.replace(/\.ts$/, "")}";`)
    .join("\n")}\n`,
);

if (check) {
  const stale = [];
  for (const [name, text] of outputs) {
    let current = null;
    try {
      // A Windows checkout may carry CRLF; the content is what matters.
      current = (await readFile(join(outDir, name), "utf-8")).replace(/\r\n/g, "\n");
    } catch {
      // missing = stale
    }
    if (current !== text) stale.push(name);
  }
  const extra = (await readdir(outDir)).filter((name) => name.endsWith(".ts") && !outputs.has(name));
  if (stale.length || extra.length || failures.length) {
    if (stale.length) console.error(`stale or missing: ${stale.map((n) => `src/schemas/${n}`).join(", ")}`);
    if (extra.length)
      console.error(`not generated from any schema: ${extra.map((n) => `src/schemas/${n}`).join(", ")}`);
    if (failures.length) console.error(`schemas that failed to compile: ${failures.join(", ")}`);
    console.error("src/schemas is out of date with rapidtriage/schemas; run npm run gen:schemas");
    process.exit(1);
  }
  console.log(`schemas: ${outputs.size - 1}/${files.length} up to date`);
} else {
  await mkdir(outDir, { recursive: true });
  for (const [name, text] of outputs) {
    await writeFile(join(outDir, name), text, "utf-8");
    if (name !== "index.ts") console.log(`generated src/schemas/${name}`);
  }
  console.log(`schemas: ${outputs.size - 1}/${files.length} generated`);
}
