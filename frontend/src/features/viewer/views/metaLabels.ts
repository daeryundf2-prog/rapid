/** "m365_export_parser_manifest" → "M365 내보내기 파서 매니페스트"; null when the family is unknown. */
function familyLabel(key: string): string | null {
  for (const [suffix, suffixLabel] of SUFFIX_LABELS) {
    if (key === suffix) return suffixLabel;
    if (!key.endsWith(`_${suffix}`)) continue;
    const prefix = key.slice(0, -(suffix.length + 1));
    const prefixLabel = PREFIX_LABELS[prefix];
    if (prefixLabel) return `${prefixLabel} ${suffixLabel}`;
  }
  return null;
}

/** Korean label of a record key, or null when there is none (the caller humanises the key). */
export function metaLabel(key: string): string | null {
  const direct = META_LABELS[key] ?? FIELD_LABELS[key];
  if (direct) return direct;
  if (key.endsWith("_hash")) {
    const base = metaLabel(key.slice(0, -"_hash".length));
    return base ? `${base} 해시` : null;
  }
  if (key.endsWith("_count")) {
    const base = META_LABELS[key.slice(0, -"_count".length)];
    if (base) return `${base} 수`;
  }
  return familyLabel(key);
}

/**
 * Labels for the keys of ONE section (review B2-8): keys that share a label (timestamp / time →
 * 시각, user / user_name → 사용자 …) read "라벨", "라벨 (2)" … so the visible text tells them apart
 * without a raw key (R7 L3; the raw key stays the tooltip). null = no label (the raw key is shown).
 */
export function sectionLabels(keys: readonly string[]): Map<string, string | null> {
  const labels = new Map(keys.map((key) => [key, metaLabel(key)] as const));
  const uses = new Map<string, number>();
  for (const label of labels.values()) if (label) uses.set(label, (uses.get(label) ?? 0) + 1);
  const seen = new Map<string, number>();
  return new Map(
    [...labels].map(([key, label]) => {
      if (!label || (uses.get(label) ?? 0) < 2) return [key, label];
      const nth = (seen.get(label) ?? 0) + 1;
      seen.set(label, nth);
      return [key, nth > 1 ? `${label} (${nth})` : label];
    }),
  );
}

