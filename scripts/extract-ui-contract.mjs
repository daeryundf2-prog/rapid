#!/usr/bin/env node
/**
 * User-contract extractor (R8 T-001, appendix D).
 *
 * Scans the frontend source, its vitest files and the e2e specs, and emits what users and their
 * automation lean on:
 *   - accessible names used by tests (`getByRole(..., { name })`, `getByLabel`, `getByLabelText`),
 *     classified `keep` (an e2e spec uses it) / `alias` (vitest only), plus whether the literal is
 *     present in the non-test source;
 *   - browser storage keys (`rapidtriage.*`, `rt.*` literals in the non-test source);
 *   - `KEY_MAP` (contracts/command.ts) and the popout message kinds (viewer/popout/protocol.ts);
 *   - every `data-testid` (reference list only — testids are NOT frozen, D65; constants come in T-157).
 *
 * Usage (from the repo root or anywhere):
 *   node scripts/extract-ui-contract.mjs            # JSON report on stdout
 *   node scripts/extract-ui-contract.mjs --write    # regenerate the generated block of uiContract.ts
 *   node scripts/extract-ui-contract.mjs --check    # exit 1 when uiContract.ts is stale (QA-111 ②)
 *
 * No dependencies: plain regex over the source text.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const FRONTEND = join(ROOT, "frontend");
const SRC = join(FRONTEND, "src");
const E2E = join(FRONTEND, "e2e");
const CONTRACT_FILE = join(SRC, "contracts", "uiContract.ts");
const BEGIN =
  "// <extract-ui-contract:begin> — generated by scripts/extract-ui-contract.mjs --write; do not edit.";
const END = "// <extract-ui-contract:end>";

function walk(dir, accept) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name.startsWith(".")) continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(path, accept));
    else if (accept(entry.name)) out.push(path);
  }
  return out.sort();
}

const isTs = (name) => /\.(ts|tsx)$/.test(name);
const isTest = (name) => /\.test\.(ts|tsx)$/.test(name);
const read = (path) => readFileSync(path, "utf8").replace(/\r\n/g, "\n");
const rel = (path) => relative(ROOT, path).replace(/\\/g, "/");

const STRING = String.raw`"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*'|\/(?![/*])(?:[^/\\\n]|\\.)+\/[a-z]*`;

/** A name literal → `{ name, pattern }` (pattern = regex literal), or null for a dynamic name. */
function literal(token) {
  if (!token) return null;
  if (token.startsWith('"')) return { name: JSON.parse(token), pattern: false };
  if (token.startsWith("'")) {
    const body = token.slice(1, -1).replace(/\\'/g, "'").replace(/"/g, '\\"');
    return { name: JSON.parse(`"${body}"`), pattern: false };
  }
  return { name: token, pattern: true };
}

const ROLE_CALL =
  /\b(?:get|getAll|query|queryAll|find|findAll)ByRole\(\s*(["'])([\w-]+)\1\s*(?:,\s*\{([^{}]*)\})?/g;
const NAME_OPTION = new RegExp(String.raw`\bname:\s*(${STRING})`);
const LABEL_CALL = new RegExp(
  String.raw`\b(?:getByLabel|(?:get|getAll|query|queryAll|find|findAll)ByLabelText)\(\s*(${STRING})`,
  "g",
);

/** Accessible names a test file uses: `[{ role, name, pattern }]` (`role` "(label)" for label queries). */
function namesIn(text) {
  const out = [];
  for (const match of text.matchAll(ROLE_CALL)) {
    const option = match[3] ? NAME_OPTION.exec(match[3]) : null;
    const lit = literal(option?.[1]);
    if (lit) out.push({ role: match[2], ...lit });
  }
  for (const match of text.matchAll(LABEL_CALL)) {
    const lit = literal(match[1]);
    if (lit) out.push({ role: "(label)", ...lit });
  }
  return out;
}

function extract() {
  // uiContract.ts itself is not "source": its tables would make every name look present.
  const sourceFiles = walk(SRC, (name) => isTs(name) && !isTest(name)).filter(
    (path) => path !== CONTRACT_FILE,
  );
  const testFiles = walk(SRC, isTest);
  const e2eFiles = walk(E2E, (name) => name.endsWith(".spec.ts"));
  const source = sourceFiles.map((path) => [path, read(path)]);
  const sourceText = source.map(([, text]) => text).join("\n");

  // --- accessible names -----------------------------------------------------------------------
  const table = new Map();
  const add = (entry, from) => {
    const key = `${entry.role}\u0000${entry.name}`;
    const row = table.get(key) ?? { ...entry, e2e: 0, vitest: 0 };
    row[from] += 1;
    table.set(key, row);
  };
  for (const path of e2eFiles) for (const entry of namesIn(read(path))) add(entry, "e2e");
  for (const path of testFiles) for (const entry of namesIn(read(path))) add(entry, "vitest");
  const a11yNames = [...table.values()]
    .map((row) => ({
      role: row.role,
      name: row.name,
      pattern: row.pattern,
      use: row.e2e ? "keep" : "alias",
      inSource: !row.pattern && sourceText.includes(row.name),
    }))
    .sort((a, b) => (a.role === b.role ? cmp(a.name, b.name) : cmp(a.role, b.role)));

  // --- storage keys ---------------------------------------------------------------------------
  const storage = new Set();
  for (const [, text] of source) {
    for (const match of text.matchAll(
      /["`]((?:rapidtriage|rt)\.[A-Za-z0-9_.-]+(?:\$\{[^}]*\}[A-Za-z0-9_.-]*)*)["`]/g,
    )) {
      storage.add(match[1].replace(/\$\{[^}]*\}/g, "<…>"));
    }
  }

  // --- KEY_MAP --------------------------------------------------------------------------------
  const command = read(join(SRC, "contracts", "command.ts"));
  const keyBlock = /export const KEY_MAP = \{([\s\S]*?)\n\} as const;/.exec(command)?.[1] ?? "";
  const keyMap = Object.fromEntries(
    [...keyBlock.matchAll(/^\s*(\w+):\s*"((?:[^"\\]|\\.)*)",/gm)].map((m) => [m[1], JSON.parse(`"${m[2]}"`)]),
  );

  // --- popout message kinds -------------------------------------------------------------------
  const protocol = read(join(SRC, "features", "viewer", "popout", "protocol.ts"));
  const union = (name) => {
    const block = new RegExp(String.raw`export type ${name} =([\s\S]*?);\n`).exec(protocol)?.[1] ?? "";
    return [...block.matchAll(/type:\s*"([\w-]+)"/g)].map((m) => m[1]);
  };
  const stateType = /export interface PopoutState \{\s*type:\s*"([\w-]+)"/.exec(protocol)?.[1];
  const popout = {
    mainToPopout: [...new Set([...(stateType ? [stateType] : []), ...union("MainToPopout")])],
    popoutToMain: union("PopoutToMain"),
  };

  // --- testids (reference list, not frozen) ---------------------------------------------------
  const testIds = new Set();
  for (const [, text] of source) {
    for (const match of text.matchAll(/data-testid=(?:"([^"]+)"|\{\s*["`]([^"`]+)["`]\s*\})/g)) {
      testIds.add((match[1] ?? match[2]).replace(/\$\{[^}]*\}/g, "<…>"));
    }
  }

  return {
    files: { source: sourceFiles.length, vitest: testFiles.length, e2e: e2eFiles.map(rel) },
    a11yNames,
    storageKeys: [...storage].sort(cmp),
    keyMap,
    popout,
    testIds: [...testIds].sort(cmp),
  };
}

function cmp(a, b) {
  return a < b ? -1 : a > b ? 1 : 0;
}

/** The generated block of uiContract.ts (accessible-name table only; the rest is hand-curated). */
function generatedBlock(report) {
  const rows = report.a11yNames.map(
    (row) =>
      `  [${JSON.stringify(row.role)}, ${JSON.stringify(row.name)}, "${row.use}", ${row.pattern ? '"pattern"' : row.inSource ? '"source"' : '"dynamic"'}],`,
  );
  return [
    BEGIN,
    "/**",
    ' * Accessible names the tests query: [role, name, use, presence]. `role` "(label)" = getByLabel /',
    " * getByLabelText. use: `keep` = an e2e spec uses it (R8 does not change it), `alias` = vitest only (a",
    " * task that changes the screen may change it together with its test). presence: `source` = the literal",
    " * is in the non-test source, `dynamic` = composed at runtime, `pattern` = the test matches a regex.",
    " */",
    "// biome-ignore format: generated table, one row per line",
    "export const A11Y_NAME_TABLE: readonly A11yNameRow[] = [",
    ...rows,
    "];",
    END,
  ].join("\n");
}

function main() {
  const args = new Set(process.argv.slice(2));
  const report = extract();
  if (args.has("--write") || args.has("--check")) {
    const current = read(CONTRACT_FILE);
    const start = current.indexOf(BEGIN);
    const end = current.indexOf(END);
    if (start < 0 || end < start) {
      console.error(`extract-ui-contract: markers not found in ${rel(CONTRACT_FILE)}`);
      process.exit(2);
    }
    const next = current.slice(0, start) + generatedBlock(report) + current.slice(end + END.length);
    if (args.has("--check")) {
      if (next !== current) {
        console.error(
          `extract-ui-contract: ${rel(CONTRACT_FILE)} is stale — run node scripts/extract-ui-contract.mjs --write`,
        );
        process.exit(1);
      }
      console.log(`extract-ui-contract: ok (${report.a11yNames.length} accessible names)`);
      return;
    }
    if (next !== current) writeFileSync(CONTRACT_FILE, next, "utf8");
    console.log(`extract-ui-contract: wrote ${report.a11yNames.length} accessible names`);
    return;
  }
  process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
}

main();
